#!/usr/bin/env python3
"""Deterministic frontend build, using the upstream release's bundled assets.

No Node/Ruby pipeline required. Controller bindings and scripts are retained;
web/layout.js builds the new presentation around them.
"""
from pathlib import Path
import gzip
import re

ROOT = Path(__file__).resolve().parents[1]
PAGES = {
    'index': ('index.htm', 'Dashboard', 'data_index_htm_gz'),
    'control': ('control.htm', 'Fermentation profiles', 'control_htm_gz'),
    'log': ('logging.htm', 'Logging', 'logging_htm_gz'),
    'setup': ('setup.htm', 'Sensors & relays', 'setup_htm_gz'),
    'config': ('config.htm', 'Settings', 'config_htm_gz'),
    'gdc': ('gravity.htm', 'Hydrometers', 'gravity_htm_gz'),
    'gdc_e32': ('gravity.htm', 'Hydrometers', 'gravity_htm_gz'),
    'pressure': ('pressure.htm', 'Pressure', 'pressure_htm_gz'),
    'backup': ('backup.htm', 'Backup & restore', 'backup_htm_gz'),
}

def build():
    theme = (ROOT / 'web/theme.css').read_text()
    output = ROOT / 'web/dist'
    output.mkdir(exist_ok=True)
    for key, (url, title, symbol) in PAGES.items():
        html = (ROOT / f'web/upstream/english_{key}_htm.html').read_text()
        html = re.sub(r'<link[^>]+fonts.googleapis.com[^>]*>', '', html)
        html = re.sub(r'<title>.*?</title>', f'<title>WebFerment · {title}</title>', html, flags=re.S)
        html = html.replace('</head>', f'<style>{theme}</style></head>')
        icons = {
            'index': '<rect x="3" y="3" width="7" height="7" rx="1"/><rect x="14" y="3" width="7" height="7" rx="1"/><rect x="3" y="14" width="7" height="7" rx="1"/><rect x="14" y="14" width="7" height="7" rx="1"/>',
            'control': '<path d="M3 17h5v-5h6V6h7M3 21h18"/>',
            'log': '<path d="M5 3h14v18H5zM8 8h8M8 12h8M8 16h5"/>',
            'setup': '<path d="M8 3v5M16 3v5M5 8h14v4a7 7 0 0 1-14 0zM12 19v3"/>',
            'config': '<path d="M4 7h16M4 17h16M8 4v6M16 14v6"/>',
            'gdc_e32': '<path d="M10 3h4v9l4 7a2 2 0 0 1-2 2H8a2 2 0 0 1-2-2l4-7zM9 16h6"/>',
            'pressure': '<path d="M4 18a9 9 0 1 1 16 0M12 13l5-5M8 18h8"/>',
            'backup': '<path d="M4 8h16v13H4zM6 3h12v5M12 12v5m-3-3 3 3 3-3"/>',
        }
        def navigation(keys):
            items = []
            for k in keys:
                path, label, _ = PAGES[k]
                active = ' aria-current="page"' if path == url else ''
                icon = f'<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" aria-hidden="true">{icons[k]}</svg>'
                items.append(f'<a href="/{path}"{active}>{icon}<span>{label}</span></a>')
            return ''.join(items)
        sidebar = '<aside class="wf-sidebar"><div class="wf-brand"><span class="wf-brand-mark"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" aria-hidden="true"><path d="M8 3h8M10 3v5l-4 9a3 3 0 0 0 3 4h6a3 3 0 0 0 3-4l-4-9V3M8 15h8"/><path d="M10 17h4"/></svg></span>WebFerment <span class="wf-version">0.5</span></div><p>Fermentation controller.</p><div class="wf-nav-group">FERMENTATION</div><nav aria-label="Fermentation navigation">' + navigation(['index', 'control', 'log', 'gdc_e32']) + '</nav><div class="wf-nav-group">CONTROLLER</div><nav aria-label="Controller navigation">' + navigation(['setup', 'config', 'pressure', 'backup']) + '</nav><footer>Based on <a href="https://github.com/vitotai/BrewPiLess" target="_blank" rel="noopener noreferrer">BrewPiLess by vitotai</a><p>Built on the BrewPi fermentation engine.</p><div class="wf-controller-label">ESP32-C3 / Arduino<br>WebFerment UI 0.5</div></footer></aside>'
        html = re.sub(r'(<body[^>]*>)', lambda m: m[0][:-1] + f' data-page="{key}">' + sidebar, html, count=1)
        layout = (ROOT / 'web/layout.js').read_text()
        html = html.replace('</body>', f'<script>{layout}</script></body>')
        # Keep upstream's live hostname update and protocol intact.
        packed = gzip.compress(html.encode(), compresslevel=9, mtime=0)
        (output / f'{key}.html').write_text(html)
        rows = [', '.join(f'0x{x:02x}' for x in packed[i:i+16]) for i in range(0, len(packed), 16)]
        (ROOT / f'WebFerment/src/english_{key}_htm.h').write_text('// Generated by scripts/build_web.py; edit web/theme.css, web/layout.js or web/upstream.\n'
            + f'const unsigned char {symbol}[] PROGMEM = {{\n' + ',\n'.join(rows) + '\n};\n')
        print(f'{url}: {len(packed)} compressed bytes')

if __name__ == '__main__':
    build()
